<#
.SYNOPSIS
  PREPARATION MACHINE (Internet required): pull the exact pinned images, record their
  immutable digests, and export them with 'docker save' for the offline handover package.

.DESCRIPTION
  Never substitutes versions: if an exact tag cannot be pulled, or a digest differs from an
  existing lock entry, the script STOPS. Writes:
    <OutDir>\images\*.tar, <OutDir>\images\SHA256SUMS.txt
    deploy\offline\images.lock.json (repository, tag, digest, image id, os/arch, size, archive hash)
  Reads no secrets and changes nothing outside Docker's image store, OutDir and the lock file.

.EXAMPLE
  .\Export-TomYum-OfflineImages.ps1 -OutDir D:\TYBC-package -GatewayImage nginx:1.30.0-alpine -NodeImage node:22.22.0-alpine
  (Choose the gateway/node tags deliberately; floating tags such as 'latest', 'stable' or 'alpine' are refused.)
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)][string]$OutDir,
  [Parameter(Mandatory = $true)][string]$GatewayImage,
  [string]$NodeImage,
  [string]$LockFile
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path
if (-not $LockFile) { $LockFile = Join-Path $repo 'deploy\offline\images.lock.json' }
$imgDir = Join-Path $OutDir 'images'
New-Item -ItemType Directory -Force -Path $imgDir | Out-Null

$wanted = @(
  @{ role = 'db';      ref = 'supabase/postgres:17.11.0.003' },
  @{ role = 'auth';    ref = 'supabase/gotrue:v2.197.0' },
  @{ role = 'rest';    ref = 'postgrest/postgrest:v14.18' },
  @{ role = 'gateway'; ref = $GatewayImage }
)
if ($NodeImage) { $wanted += @{ role = 'node'; ref = $NodeImage } }
foreach ($w in $wanted) {
  $tag = ($w.ref -split ':')[-1]
  if ($w.ref -notmatch ':' -or $tag -match '^(latest|stable|mainline|alpine|lts|current)$' -or $tag -notmatch '\d+\.\d+') {
    throw "Refusing floating or unversioned tag '$($w.ref)'. Use an exact version tag."
  }
}

$old = $null
if (Test-Path -LiteralPath $LockFile) { $old = Get-Content -LiteralPath $LockFile -Raw | ConvertFrom-Json }

$entries = @()
foreach ($w in $wanted) {
  Write-Host "pull  $($w.ref)"
  & docker pull --platform linux/amd64 $w.ref
  if ($LASTEXITCODE -ne 0) { throw "STOP: exact image '$($w.ref)' could not be pulled. Do not substitute another version; report it." }
  $i = (& docker image inspect $w.ref | Out-String | ConvertFrom-Json)[0]
  $repoName = $w.ref.Substring(0, $w.ref.LastIndexOf(':'))
  $tag = $w.ref.Substring($w.ref.LastIndexOf(':') + 1)
  $rd = @($i.RepoDigests | Where-Object { $_ -like "$repoName@*" -or $_ -like "docker.io/$repoName@*" -or $_ -like "docker.io/library/$repoName@*" })
  if (-not $rd.Count) { throw "STOP: no registry digest recorded for $($w.ref)." }
  $digest = ($rd[0] -split '@')[1]
  if ($i.Architecture -ne 'amd64' -or $i.Os -ne 'linux') { throw "STOP: $($w.ref) is $($i.Os)/$($i.Architecture), expected linux/amd64." }
  if ($old) {
    $prev = @($old.images | Where-Object { $_.repository -eq $repoName -and $_.tag -eq $tag })
    if ($prev.Count -and $prev[0].digest -ne $digest) { throw "STOP: $($w.ref) now resolves to $digest but the lock has $($prev[0].digest). The tag moved upstream; do not substitute silently." }
  }
  $file = ($repoName -replace '[/:]', '_') + "_$tag.tar"
  $tar = Join-Path $imgDir $file
  Write-Host "save  $($w.ref) -> $file"
  & docker save --platform linux/amd64 -o $tar $w.ref 2>$null
  if ($LASTEXITCODE -ne 0) { & docker save -o $tar $w.ref; if ($LASTEXITCODE -ne 0) { throw "docker save failed for $($w.ref)" } }
  $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $tar).Hash.ToLowerInvariant()
  $entries += [pscustomobject][ordered]@{
    role = $w.role; repository = $repoName; tag = $tag; digest = $digest; imageId = $i.Id
    os = $i.Os; architecture = $i.Architecture; sizeBytes = [long]$i.Size
    archive = "images/$file"; archiveBytes = (Get-Item -LiteralPath $tar).Length; archiveSha256 = $hash
  }
}

$lock = [ordered]@{
  schema = 1
  note = 'Generated by Export-TomYum-OfflineImages.ps1 on the preparation machine. Do not edit by hand.'
  generatedUtc = [DateTime]::UtcNow.ToString('o')
  dockerServer = (& docker version --format '{{.Server.Version}}')
  images = $entries
}
$lock | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $LockFile -Encoding UTF8
($entries | ForEach-Object { "$($_.archiveSha256)  $($_.archive)" }) | Set-Content -LiteralPath (Join-Path $OutDir 'images\SHA256SUMS.txt') -Encoding ASCII
$entries | Format-Table role, repository, tag, @{ n = 'digest'; e = { $_.digest.Substring(0, 19) + '...' } }, architecture, @{ n = 'MB'; e = { [math]::Round($_.sizeBytes / 1MB) } } -AutoSize
Write-Host "Lock written: $LockFile"
